<?php
error_reporting(0);
ini_set('display_errors', 0);

header("Access-Control-Allow-Origin: *");
header("Access-Control-Allow-Methods: GET, POST, OPTIONS");
header("Access-Control-Allow-Headers: Content-Type, Authorization, X-Requested-With");
header("Content-Type: application/json; charset=UTF-8");

if ($_SERVER['REQUEST_METHOD'] == 'OPTIONS') { http_response_code(200); exit(); }

include "config.php";

// ════════════════════════════════════════════════════════
//  POST — Cashier confirms a pending order
// ════════════════════════════════════════════════════════
$input = file_get_contents("php://input");
$data  = json_decode($input, true);

if ($_SERVER['REQUEST_METHOD'] === 'POST' && isset($data['order_id'])) {
    $order_id = $conn->real_escape_string($data['order_id']);
    $conn->begin_transaction();
    try {
        // Order lives in sales table (written by save_order.php)
        $q = $conn->query("SELECT * FROM sales WHERE id='$order_id' AND status='Pending'");
        $order = $q ? $q->fetch_assoc() : null;
        if (!$order) throw new Exception("Order not found or already processed.");

        // Keep existing receipt_no (already generated by save_order.php)
        $receipt_no = !empty($order['receipt_no'])
                      ? $order['receipt_no']
                      : "REC-" . strtoupper(substr(md5(uniqid()), 0, 8));

        // Mark as Completed
        $conn->query("UPDATE sales SET status='Completed', receipt_no='$receipt_no' WHERE id='$order_id'");

        // Deduct stock
        $items = $conn->query("SELECT product_id, quantity FROM transaction_items WHERE sale_id='$order_id'");
        if ($items) {
            while ($item = $items->fetch_assoc()) {
                $pid = intval($item['product_id']);
                $qty = intval($item['quantity']);
                $conn->query("UPDATE products SET quantity = quantity - $qty WHERE id = $pid");
            }
        }

        $conn->commit();
        echo json_encode(["success" => true, "message" => "Processed!", "receipt_no" => $receipt_no]);
    } catch (Exception $e) {
        $conn->rollback();
        echo json_encode(["success" => false, "message" => $e->getMessage()]);
    }
    exit;
}

// ════════════════════════════════════════════════════════
//  GET — Fetch dashboard data
// ════════════════════════════════════════════════════════
$response = ["pending_orders" => [], "transactions" => []];

// 1. Pending Orders — status = 'Pending' from sales table
$q1 = $conn->query("
    SELECT
        s.id,
        IFNULL(s.customer_name, 'Walk-in')  AS customer_name,
        s.total,
        s.receipt_no,
        s.payment_method                     AS payment_type,
        GROUP_CONCAT(
            CONCAT(ti.quantity, 'x ', IFNULL(p.name,'Unknown'))
            ORDER BY p.name SEPARATOR ', '
        ) AS medicines
    FROM sales s
    LEFT JOIN transaction_items ti ON s.id = ti.sale_id
    LEFT JOIN products p           ON ti.product_id = p.id
    WHERE s.status = 'Pending'
    GROUP BY s.id
    ORDER BY s.id DESC
");
if ($q1) {
    while ($row = $q1->fetch_assoc()) {
        $row['total'] = number_format((float)$row['total'], 2, '.', '');
        $response["pending_orders"][] = $row;
    }
}

// 2. Recent Transactions — status = 'Completed' ONLY
$q2 = $conn->query("
    SELECT
        s.id,
        s.receipt_no,
        IFNULL(s.customer_name, 'Walk-in')  AS customer_name,
        s.total,
        s.status,
        s.sale_date,
        s.payment_method                     AS payment_type,
        GROUP_CONCAT(
            CONCAT(ti.quantity, 'x ', IFNULL(p.name,'Product'))
            ORDER BY p.name SEPARATOR ', '
        ) AS medicines
    FROM sales s
    LEFT JOIN transaction_items ti ON s.id = ti.sale_id
    LEFT JOIN products p           ON ti.product_id = p.id
    WHERE s.status = 'Completed'
    GROUP BY s.id
    ORDER BY s.id DESC
");
if ($q2) {
    while ($row = $q2->fetch_assoc()) {
        $row['total']     = number_format((float)$row['total'], 2, '.', '');
        $row['sale_date'] = date("M d, Y h:i A", strtotime($row['sale_date']));
        $response["transactions"][] = $row;
    }
}

echo json_encode($response);
?>